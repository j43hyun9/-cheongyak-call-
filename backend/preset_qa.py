def lookup(user_message: str) -> str | None:
    """정규화 매칭 후 사전 답변 반환. 없으면 None."""
    key = _norm(user_message)
    # 직접 매칭
    if key in _ANSWERS:
        return _ANSWERS[key]
    # 별칭 매칭
    canonical = _ALIASES.get(key)
    if canonical:
        return _ANSWERS.get(canonical)
    # 부분 포함 매칭 (키가 메시지 안에 포함되는 경우)
    for k, answer in _ANSWERS.items():
        if k in key or key in k:
            return answer
    return None
